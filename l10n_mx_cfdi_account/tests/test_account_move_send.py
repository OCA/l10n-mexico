import base64
from unittest.mock import patch

from odoo.tests import tagged

from .common_cfdi_document import CFDIDocumentTestCommon


@tagged("post_install", "-at_install")
class TestAccountMoveSend(CFDIDocumentTestCommon):
    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.template = cls.env.ref("account.email_template_edi_invoice")
        cls.invoice = cls.env["account.move"].create(
            {
                "move_type": "out_invoice",
                "partner_id": cls.partner.id,
                "invoice_line_ids": [
                    (0, 0, {"name": "Service", "quantity": 1, "price_unit": 100.0})
                ],
            }
        )

    def _widget_items(self):
        widget = self.env["account.move.send"]._get_default_mail_attachments_widget(
            self.invoice, self.template
        )
        return {item["name"]: item for item in widget if not item.get("placeholder")}

    def test_cfdi_xml_added_to_attachments_widget(self):
        self._publish_cfdi(
            self.invoice,
            xml_file=base64.b64encode(b"<cfdi:Comprobante/>"),
            xml_filename="cfdi.xml",
            pdf_file=base64.b64encode(b"%PDF-1.4 test"),
            pdf_filename="cfdi.pdf",
        )
        items = self._widget_items()
        self.assertEqual(items["cfdi.xml"]["mimetype"], "application/xml")
        # the PDF generated by Odoo is the only one sent, not the CFDI PDF
        self.assertNotIn("cfdi.pdf", items)
        # a second call reuses the attachment instead of duplicating it
        self.assertEqual(
            items["cfdi.xml"]["id"], self._widget_items()["cfdi.xml"]["id"]
        )

    def test_no_cfdi_xml_when_not_published(self):
        self._publish_cfdi(
            self.invoice, state="draft", xml_file=base64.b64encode(b"<x/>")
        )
        self.assertFalse([n for n in self._widget_items() if n.endswith(".xml")])

    def _recover_xml(self, content, **doc_vals):
        document = self._publish_cfdi(
            self.invoice, tracking_id="trk-1", xml_filename="rec.xml", **doc_vals
        )
        service_model = type(self.issuer.service_id)
        with patch.object(
            service_model, "get_cfdi_xml", return_value={"Content": content}
        ):
            items = self._widget_items()
        return document, items

    def test_missing_xml_recovered_from_pac_bytes(self):
        document, items = self._recover_xml(b"<cfdi:Comprobante/>")
        self.assertIn("rec.xml", items)
        self.assertEqual(base64.b64decode(document.xml_file), b"<cfdi:Comprobante/>")

    def test_missing_xml_recovered_from_pac_str(self):
        document, items = self._recover_xml("<cfdi:Comprobante/>")
        self.assertIn("rec.xml", items)
        self.assertEqual(base64.b64decode(document.xml_file), b"<cfdi:Comprobante/>")

    def test_missing_xml_recovered_default_filename(self):
        document = self._publish_cfdi(self.invoice, tracking_id="trk-1")
        with patch.object(
            type(self.issuer.service_id),
            "get_cfdi_xml",
            return_value={"Content": b"<x/>"},
        ):
            self._widget_items()
        self.assertTrue(document.xml_filename.endswith(".xml"))

    def test_pac_failure_does_not_block_widget(self):
        self._publish_cfdi(self.invoice, tracking_id="trk-1")
        with patch.object(
            type(self.issuer.service_id), "get_cfdi_xml", side_effect=Exception("x")
        ):
            items = self._widget_items()
        self.assertFalse([n for n in items if n.endswith(".xml")])
