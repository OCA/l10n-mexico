import base64
import logging

from odoo import api, models

_logger = logging.getLogger(__name__)


class AccountMoveSend(models.AbstractModel):
    _inherit = "account.move.send"

    @api.model
    def _get_default_mail_attachments_widget(
        self,
        move,
        mail_template,
        invoice_edi_format=None,
        extra_edis=None,
        pdf_report=None,
    ):
        res = super()._get_default_mail_attachments_widget(
            move,
            mail_template,
            invoice_edi_format=invoice_edi_format,
            extra_edis=extra_edis,
            pdf_report=pdf_report,
        )
        existing_ids = {item.get("id") for item in res if item.get("id")}
        for attachment in self._l10n_mx_cfdi_get_move_attachments(move):
            if attachment.id in existing_ids:
                continue
            res.append(
                {
                    "id": attachment.id,
                    "name": attachment.name,
                    "mimetype": attachment.mimetype,
                    "placeholder": False,
                    "protect_from_deletion": True,
                    "manual": False,
                }
            )
        return res

    @api.model
    def _l10n_mx_cfdi_get_move_attachments(self, move):
        """Return the XML attachment of the published CFDI of ``move``.

        The PDF is left out on purpose: the invoice PDF generated by Odoo is the
        one that must be sent. A missing XML is recovered from the PAC (no PDF is
        rendered or requested). Failures
        are logged and never block the sending of the invoice.
        """
        attachments = self.env["ir.attachment"]
        document = move.cfdi_document_id
        if not document or document.state != "published":
            return attachments
        if not document.xml_file and document.tracking_id:
            self._l10n_mx_cfdi_recover_xml(document)
        if document.xml_file:
            attachments |= self._l10n_mx_cfdi_sync_attachment(
                move,
                document.xml_filename or f"{document.name}.xml",
                document.xml_file,
                "application/xml",
            )
        return attachments

    @api.model
    def _l10n_mx_cfdi_recover_xml(self, document):
        try:
            res = document.issuer_id.service_id.sudo().get_cfdi_xml(
                document.tracking_id
            )
            content = res.get("Content") or b""
            if isinstance(content, str):
                content = content.encode("utf-8")
            if content:
                document.xml_file = base64.b64encode(content)
                document.xml_filename = (
                    document.xml_filename
                    or f"{document.name or document.uuid or document.id}.xml"
                )
        except Exception:
            _logger.warning(
                "Could not recover CFDI XML of %s",
                document.display_name,
                exc_info=True,
            )

    @api.model
    def _l10n_mx_cfdi_sync_attachment(self, move, filename, data, mimetype):
        Attachment = self.env["ir.attachment"]
        vals = {
            "name": filename,
            "datas": data,
            "res_model": move._name,
            "res_id": move.id,
            "type": "binary",
            "mimetype": mimetype,
        }
        attachment = Attachment.search(
            [
                ("res_model", "=", move._name),
                ("res_id", "=", move.id),
                ("name", "=", filename),
                ("mimetype", "=", mimetype),
            ],
            limit=1,
        )
        if attachment:
            attachment.write({"datas": data})
            return attachment
        return Attachment.create(vals)
